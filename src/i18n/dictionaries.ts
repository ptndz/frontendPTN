/**
 * P5b — i18n frontend (vi/en), tự làm, 0 dependency mới.
 *
 * Vì sao không dùng next-i18next / next-intl:
 * - Repo dùng pages-router (`src/pages`), không dùng app-router; next-i18next
 *   đòi sửa next.config + bọc appWithTranslation + gọi serverSideTranslations
 *   ở mọi page có getServerSideProps — nặng và dễ vỡ build hơn lợi ích đem lại.
 * - next-intl 4.x chủ yếu cho app-router; bản pages-router của nó cũng cần
 *   thêm provider + config.
 * - Nhu cầu hiện tại chỉ là: 2 ngôn ngữ, đổi ngay phía client, lưu lựa chọn,
 *   fallback về vi. Một Context + dictionary gõ chặt bằng TS là đủ, không
 *   thêm dep, không đổi config, không đổi behaviour.
 *
 * Quy ước:
 * - Ngôn ngữ mặc định: vi. Bản vi giữ text cũ đang hiển thị; các lỗi
 *   chính tả cũ ("Wright a comment ...", "loi he thong") đã được sửa
 *   ngày 2026-11-11 (bug 5) thành "Write a comment ..." / "Lỗi hệ thống".
 * - Key dạng đường dẫn chấm, tra bằng `t("nav.home")`; thiếu key ở locale
 *   đang chọn thì fallback về vi, rồi mới trả về chính key đó.
 * - Thêm key mới: thêm vào CẢ `vi` và `en` — TS ép `en` phải cùng shape
 *   với `vi` (`en: Dictionary`), thiếu key là lỗi typecheck.
 * - Plural/date/number: không tự làm — dùng Intl/moment đã có sẵn; provider
 *   đồng bộ `moment.locale()` theo locale (xem I18nProvider).
 */

